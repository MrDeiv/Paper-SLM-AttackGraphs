#!/usr/bin/env python3
"""
Plot SQuAD asymmetric hybrid retrieval results from CSV files.

This script performs no retrieval and no Ragas scoring. It reads the aggregate
CSV generated by `run_squad_asymmetric_hybrid_eval.py` and writes paper-friendly
PDF figures. Optionally, it can also read the original component CSV produced by
`run_squad_ragas_pipeline_eval.py` to compare BM25@k, Vector@k, and the best
asymmetric hybrid configuration.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot SQuAD asymmetric hybrid retrieval CSV outputs.")
    parser.add_argument(
        "--input-dir",
        default=None,
        help="Directory containing asymmetric_hybrid_metrics.csv. If provided, --asymmetric-csv defaults to <input-dir>/asymmetric_hybrid_metrics.csv.",
    )
    parser.add_argument("--asymmetric-csv", default=None, help="Path to asymmetric_hybrid_metrics.csv")
    parser.add_argument(
        "--component-csv",
        default=None,
        help="Optional path to component_by_k.csv from the main SQuAD retrieval run.",
    )
    parser.add_argument("--out-dir", default=None, help="Output figures directory. Default: <input-dir>/figures")
    parser.add_argument("--final-k", type=int, default=None, help="Final k to use for by-weight plot. Default: best by selection metric")
    parser.add_argument("--bm25-k", type=int, default=100, help="BM25 k for component comparison. Default: 100")
    parser.add_argument("--vector-k", type=int, default=50, help="Vector k for component comparison. Default: 50")
    parser.add_argument("--selection-metric", default="ragas_f2", help="Metric used to identify best configurations. Default: ragas_f2")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    input_dir = Path(args.input_dir) if args.input_dir else None
    asymmetric_csv = Path(args.asymmetric_csv) if args.asymmetric_csv else (input_dir / "asymmetric_hybrid_metrics.csv" if input_dir else None)
    if asymmetric_csv is None:
        raise ValueError("Provide either --input-dir or --asymmetric-csv")
    if not asymmetric_csv.exists():
        raise FileNotFoundError(asymmetric_csv)

    out_dir = Path(args.out_dir) if args.out_dir else (input_dir / "figures" if input_dir else asymmetric_csv.parent / "figures")
    out_dir.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(asymmetric_csv)
    if df.empty:
        raise ValueError(f"No rows found in {asymmetric_csv}")

    metric = args.selection_metric if args.selection_metric in df.columns else "ragas_f2"
    final_k = int(args.final_k or select_best_row(df, metric)["final_k"])

    plot_weight_curves(df, final_k=final_k, path=out_dir / f"asymmetric_hybrid_by_weight_k{final_k}.pdf")
    plot_final_k_curves(df, metric=metric, path=out_dir / f"asymmetric_hybrid_{metric}_by_final_k.pdf")
    plot_precision_recall_tradeoff(df, metric=metric, path=out_dir / "asymmetric_hybrid_precision_recall_tradeoff.pdf")
    plot_context_tokens_vs_metric(df, metric=metric, path=out_dir / f"asymmetric_hybrid_context_tokens_vs_{metric}.pdf")

    summary: dict[str, Any] = {
        "asymmetric_csv": str(asymmetric_csv),
        "selection_metric": metric,
        "selected_final_k_for_weight_plot": final_k,
        "best_asymmetric": jsonable(select_best_row(df, metric)),
        "figures": [
            str(out_dir / f"asymmetric_hybrid_by_weight_k{final_k}.pdf"),
            str(out_dir / f"asymmetric_hybrid_{metric}_by_final_k.pdf"),
            str(out_dir / "asymmetric_hybrid_precision_recall_tradeoff.pdf"),
            str(out_dir / f"asymmetric_hybrid_context_tokens_vs_{metric}.pdf"),
        ],
    }

    if args.component_csv:
        component_csv = Path(args.component_csv)
        component_df = pd.read_csv(component_csv)
        if not component_df.empty:
            plot_component_vs_hybrid_summary(
                component_df=component_df,
                asymmetric_df=df,
                metric=metric,
                bm25_k=args.bm25_k,
                vector_k=args.vector_k,
                path=out_dir / f"component_vs_asymmetric_hybrid_{metric}.pdf",
            )
            summary["component_csv"] = str(component_csv)
            summary["figures"].append(str(out_dir / f"component_vs_asymmetric_hybrid_{metric}.pdf"))

    (out_dir / "plot_summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Figures written to {out_dir}")


def plot_weight_curves(df: pd.DataFrame, *, final_k: int, path: Path) -> None:
    subset = df[df["final_k"] == final_k].sort_values("bm25_weight")
    if subset.empty:
        return
    setup_matplotlib()
    fig, ax = plt.subplots(figsize=(5.8, 3.6))
    ax.plot(subset["bm25_weight"], subset["ragas_precision"], marker="o", linestyle=":", label="Ragas precision")
    ax.plot(subset["bm25_weight"], subset["ragas_recall"], marker="^", linestyle="--", label="Ragas recall")
    ax.plot(subset["bm25_weight"], subset["ragas_f1"], marker="s", linestyle="-", label="Ragas F1")
    ax.plot(subset["bm25_weight"], subset["ragas_f2"], marker="D", linestyle="-.", label="Ragas F2")
    ax.set_xlabel("BM25 weight")
    ax.set_ylabel("Score")
    ax.set_title(f"Asymmetric hybrid retrieval at final k={final_k}")
    ax.set_ylim(bottom=0)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def plot_final_k_curves(df: pd.DataFrame, *, metric: str, path: Path) -> None:
    if metric not in df.columns:
        return
    setup_matplotlib()
    fig, ax = plt.subplots(figsize=(6.0, 3.6))
    for weight, group in df.groupby("bm25_weight"):
        group = group.sort_values("final_k")
        ax.plot(group["final_k"], group[metric], marker="o", label=f"BM25 weight={weight:g}")
    ax.set_xlabel("Final fused k")
    ax.set_ylabel(metric)
    ax.set_title(f"Asymmetric hybrid {metric} by final context depth")
    ax.set_ylim(bottom=0)
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def plot_precision_recall_tradeoff(df: pd.DataFrame, *, metric: str, path: Path) -> None:
    setup_matplotlib()
    fig, ax = plt.subplots(figsize=(5.3, 3.8))
    scatter = ax.scatter(df["ragas_precision"], df["ragas_recall"], s=36)
    best = select_best_row(df, metric)
    ax.scatter([best["ragas_precision"]], [best["ragas_recall"]], s=90, marker="*")
    ax.annotate(
        f"best\nw={best['bm25_weight']:.2f}, k={int(best['final_k'])}",
        (best["ragas_precision"], best["ragas_recall"]),
        textcoords="offset points",
        xytext=(8, 8),
        fontsize=8,
    )
    ax.set_xlabel("Ragas precision")
    ax.set_ylabel("Ragas recall")
    ax.set_title("Asymmetric hybrid precision-recall trade-off")
    ax.set_xlim(left=0)
    ax.set_ylim(bottom=0)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def plot_context_tokens_vs_metric(df: pd.DataFrame, *, metric: str, path: Path) -> None:
    if metric not in df.columns:
        return
    setup_matplotlib()
    fig, ax = plt.subplots(figsize=(5.8, 3.6))
    for weight, group in df.groupby("bm25_weight"):
        group = group.sort_values("context_tokens_mean")
        ax.plot(group["context_tokens_mean"], group[metric], marker="o", label=f"BM25 weight={weight:g}")
    ax.set_xlabel("Mean context tokens")
    ax.set_ylabel(metric)
    ax.set_title(f"Context budget vs {metric}")
    ax.set_ylim(bottom=0)
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def plot_component_vs_hybrid_summary(
    *,
    component_df: pd.DataFrame,
    asymmetric_df: pd.DataFrame,
    metric: str,
    bm25_k: int,
    vector_k: int,
    path: Path,
) -> None:
    rows: list[dict[str, Any]] = []
    if "retriever" in component_df.columns and metric in component_df.columns:
        bm25 = component_df[(component_df["retriever"] == "bm25") & (component_df["k"] == bm25_k)]
        vector = component_df[(component_df["retriever"] == "vector") & (component_df["k"] == vector_k)]
        if not bm25.empty:
            rows.append({"config": f"BM25@{bm25_k}", metric: float(bm25.iloc[0][metric])})
        if not vector.empty:
            rows.append({"config": f"Vector@{vector_k}", metric: float(vector.iloc[0][metric])})

    best = select_best_row(asymmetric_df, metric)
    rows.append(
        {
            "config": f"Hybrid\nw={best['bm25_weight']:.2f}, k={int(best['final_k'])}",
            metric: float(best[metric]),
        }
    )
    plot_df = pd.DataFrame(rows)
    if plot_df.empty:
        return

    setup_matplotlib()
    fig, ax = plt.subplots(figsize=(5.2, 3.4))
    ax.bar(plot_df["config"], plot_df[metric])
    ax.set_ylabel(metric)
    ax.set_title("Component vs asymmetric hybrid retrieval")
    ax.set_ylim(bottom=0)
    for idx, value in enumerate(plot_df[metric]):
        ax.text(idx, value, f"{value:.3f}", ha="center", va="bottom", fontsize=8)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def select_best_row(df: pd.DataFrame, metric: str) -> pd.Series:
    ranked = df.sort_values(
        [metric, "ragas_f1", "mrr", "ndcg", "context_tokens_mean", "final_k"],
        ascending=[False, False, False, False, True, True],
        na_position="last",
    )
    return ranked.iloc[0]


def setup_matplotlib() -> None:
    plt.rcParams.update({"pdf.fonttype": 42, "ps.fonttype": 42, "axes.grid": True, "grid.alpha": 0.25})


def jsonable(value: Any) -> Any:
    if isinstance(value, pd.Series):
        return jsonable(value.to_dict())
    if isinstance(value, dict):
        return {str(k): jsonable(v) for k, v in value.items()}
    if isinstance(value, list):
        return [jsonable(v) for v in value]
    if isinstance(value, tuple):
        return [jsonable(v) for v in value]
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return None if np.isnan(value) else float(value)
    try:
        if pd.isna(value) and not isinstance(value, str):
            return None
    except Exception:
        pass
    return value


if __name__ == "__main__":
    main()
