#!/usr/bin/env python3
"""
Summarize temporal milestone attack graphs across runs.

This script reads graph JSON files generated by scripts/build_attack_graphs.py
and writes a CSV table suitable for final metrics or paper tables.

Example:
    python scripts/summarize_attack_graphs.py --runs outputs/pilot_runs --out outputs/final_metrics/temporal_milestone_graph_summary_by_variant.csv
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import csv
from src.graph.temporal_milestone_graph import graph_summary


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Summarize temporal milestone attack graphs across runs.")
    parser.add_argument("--runs", default="outputs/runs", help="Directory containing run output folders.")
    parser.add_argument("--run", action="append", help="Specific run_id to include. Can be repeated.")
    parser.add_argument("--graphs-subdir", default="graphs", help="Graph subdirectory inside each run folder.")
    parser.add_argument("--out", default="outputs/final_metrics/temporal_milestone_graph_summary_by_variant.csv", help="Output CSV path.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    run_dirs = _discover_run_dirs(Path(args.runs), args.run)
    rows: list[dict[str, Any]] = []

    for run_dir in run_dirs:
        graph_dir = run_dir / args.graphs_subdir
        for graph_path in sorted(graph_dir.glob("*_temporal_milestone_graph.json")):
            graph = _read_json(graph_path)
            summary = graph_summary(graph)
            summary.update(
                {
                    "run_dir": str(run_dir),
                    "graph_path": str(graph_path),
                }
            )
            rows.append(summary)

    _write_csv(args.out, rows)
    print(f"Graph summary rows: {len(rows)}")
    print(f"Output: {args.out}")


def _write_csv(path: str | Path, rows: list[dict[str, Any]]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fieldnames: list[str] = []
    seen: set[str] = set()
    for row in rows:
        for key in row.keys():
            if key not in seen:
                seen.add(key)
                fieldnames.append(key)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def _discover_run_dirs(runs_root: Path, selected_runs: list[str] | None) -> list[Path]:
    if selected_runs:
        return [runs_root / run_id for run_id in selected_runs if (runs_root / run_id).exists()]
    return sorted(path for path in runs_root.iterdir() if path.is_dir() and (path / "config.json").exists())


def _read_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    return data if isinstance(data, dict) else {}


if __name__ == "__main__":
    main()