"""
Prompt templates for the CTI enrichment pipeline.

Important design choice:
The model is asked to generate only textual content. Evidence associations are
not generated by the model. The pipeline deterministically assigns the retrieved
RAG chunks to the generated description and conditions.
"""

DESCRIPTION_PROMPT_V2 = """
You are analyzing one cyber threat intelligence attack step.

Write a concise technical description of how the attack step is performed using
only the provided evidence chunks.

Rules:
- Return JSON only.
- The description must be one or two sentences.
- Do not add facts that are absent from the evidence chunks.
- Do not cite chunk IDs in the JSON. Evidence is assigned by the pipeline.
- If the evidence is insufficient, write an empty description string.

Attack step:
{attack_step}

Evidence chunks:
{evidence_chunks}

Expected JSON schema:
{{
  "description": "The attacker creates a service to maintain persistence on the host."
}}
""".strip()


CONDITION_PROMPT_V2 = """
You are analyzing one cyber threat intelligence attack step.

Generate short, atomic preconditions and postconditions for the attack step using
only the provided evidence chunks.

Definitions:
- A precondition is a technical fact that must plausibly hold before this attack
  step can be performed.
- A postcondition is a technical fact, capability, or observable state that holds
  after this attack step succeeds.

Rules:
- Return JSON only.
- Generate as many conditions as are supported by the evidence. Do not enforce a
  fixed maximum number.
- Each condition must express exactly one technical fact.
- Each statement should be short and specific.
- Do not produce generic security advice.
- Do not repeat the attack-step name as a condition.
- Do not cite chunk IDs in the JSON. Evidence is assigned by the pipeline.
- If the evidence does not support any condition of a type, return an empty list
  for that type.

Attack step:
{attack_step}

Evidence chunks:
{evidence_chunks}

Expected JSON schema:
{{
  "preconditions": [
    "The attacker has code execution on the host."
  ],
  "postconditions": [
    "A malicious service is available for persistence."
  ]
}}
""".strip()


