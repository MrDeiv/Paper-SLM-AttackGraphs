"""
Shared dataclasses for the production CTI enrichment pipeline.

This schema intentionally keeps generated artifacts simple and deterministic:

- the model generates only textual content;
- evidence is assigned by the pipeline from the chunks retrieved by RAG;
- condition/description JSON records do not contain support labels, confidence
  labels, directness labels, or verifier labels;
- condition identifiers are deterministic and generated by the pipeline.

The frozen RAG component still uses RetrievalRecord and RetrievedChunkRecord.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field, is_dataclass
from typing import Any, Literal


ConditionType = Literal["pre", "post"]
CONDITION_TYPES = {"pre", "post", "precondition", "postcondition"}


@dataclass
class DocumentRecord:
    document_id: str
    case_id: str
    source_name: str
    source_path: str
    source_type: str
    title: str | None = None
    url: str | None = None
    publication_date: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class ChunkRecord:
    chunk_id: str
    document_id: str
    case_id: str
    chunking_strategy: str
    chunk_index: int
    text: str
    source_path: str
    token_count: int | None = None
    start_char: int | None = None
    end_char: int | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class AttackStepRecord:
    attack_step_id: str
    case_id: str
    source: str
    original_label: str
    attack_tactic: str
    input_text: str
    attack_technique_id: str | None = None
    milestone_id: str | None = None
    stix_objects: list[str] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class RetrievedChunkRecord:
    rank: int
    chunk_id: str
    document_id: str
    source_path: str
    text: str
    score: float | None = None
    bm25_score: float | None = None
    vector_score: float | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class RetrievalRecord:
    run_id: str
    case_id: str
    attack_step_id: str
    retriever: str
    chunking_strategy: str
    query: str
    top_k: int
    results: list[RetrievedChunkRecord] = field(default_factory=list)


@dataclass
class GeneratedDescription:
    """Description generated by the SLM.

    The evidence fields are not predicted by the model. They are deterministically
    assigned by the pipeline from the retrieved RAG chunks used in the prompt.
    """

    run_id: str
    case_id: str
    attack_step_id: str
    description: str
    evidence_chunk_ids: list[str]
    source_documents: list[str]
    model_id: str = ""
    prompt_version: str = ""
    generation_params: dict[str, Any] = field(default_factory=dict)


@dataclass
class GeneratedCondition:
    """Condition generated by the SLM and normalized by the pipeline.

    The model only supplies the statement and whether it is a pre- or
    post-condition. The pipeline creates the ID and attaches evidence.
    """

    condition_id: str
    run_id: str
    case_id: str
    attack_step_id: str
    condition_type: ConditionType
    statement: str
    evidence_chunk_ids: list[str]
    source_documents: list[str]
    model_id: str = ""
    prompt_version: str = ""
    generation_params: dict[str, Any] = field(default_factory=dict)


# Kept as an alias so older imports do not break. The production pipeline does
# not run a verifier and therefore does not emit verifier labels.
VerifiedCondition = GeneratedCondition


@dataclass
class RuntimeRecord:
    run_id: str
    case_id: str
    attack_step_id: str | None
    stage: str
    elapsed_ms: float
    model_id: str | None = None
    input_tokens: int | None = None
    output_tokens: int | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


def to_dict(obj: Any) -> dict[str, Any]:
    """Convert a dataclass instance or mapping to a plain dictionary."""
    if is_dataclass(obj):
        return asdict(obj)
    if isinstance(obj, dict):
        return dict(obj)
    raise TypeError(f"Cannot convert object of type {type(obj)!r} to dict")


def normalize_condition_type(value: Any) -> ConditionType | None:
    """Normalize model/legacy condition type labels to `pre` or `post`."""
    text = str(value or "").strip().lower().replace("-", "_").replace(" ", "_")
    if text in {"pre", "precondition", "pre_condition"}:
        return "pre"
    if text in {"post", "postcondition", "post_condition"}:
        return "post"
    return None


def normalize_condition_statement(value: Any) -> str:
    """Normalize a generated condition statement without changing its meaning."""
    return " ".join(str(value or "").split())


def normalize_condition_dict(raw: dict[str, Any]) -> dict[str, Any]:
    """Normalize a raw condition object returned by the model.

    Accepted raw forms include both the current minimal schema and older
    condition objects containing extra fields. Extra fields are ignored. The
    returned dictionary contains only the production fields required downstream.
    """
    condition_type = normalize_condition_type(raw.get("condition_type") or raw.get("type"))
    if condition_type is None:
        raise ValueError(f"Invalid condition_type: {raw.get('condition_type')!r}")

    statement = normalize_condition_statement(raw.get("statement") or raw.get("text") or raw.get("condition"))
    if not statement:
        raise ValueError("Condition statement cannot be empty")

    return {
        "condition_type": condition_type,
        "statement": statement,
    }
